def p(text, style=None):
    return doc.add_paragraph(text, style)

def line(label, text, spoken=False):
    para = doc.add_paragraph()
    para.paragraph_format.keep_together = True
    lead = para.add_run(label + '  ')
    lead.bold = True
    para.add_run(('“' + text.replace('“', '‘').replace('”', '’') + '”') if spoken else text)
    return para

def step(title, action, voice=None, wait=None):
    doc.add_heading(title, 2)
    line('操作', action)
    if voice:
        if isinstance(voice, str):
            voice = [voice]
        for i, text in enumerate(voice):
            line('口播' if i == 0 else '续说', text, True)
    if wait:
        line('停留', wait)

